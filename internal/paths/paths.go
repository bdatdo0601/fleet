// TLSDir returns the directory storing ACME account and TLS certificate files.
func TLSDir(stateDir string) string {
	return filepath.Join(stateDir, "tls")
}

// EdgeTokenPath returns the shared secret file authenticating loopback edge proxy requests.
func EdgeTokenPath(stateDir string) string {
	return filepath.Join(stateDir, "edge.token")
}

func homeDir() string {
	if h, err := os.UserHomeDir(); err == nil && h != "" {
		return h
	}
	return os.Getenv("HOME")
}

// HomeForUser returns the home directory for the given username, or empty string if unknown.
func HomeForUser(username string) string {
	if username == "" {
		return ""
	}
	u, err := user.Lookup(username)
	if err != nil {
		return ""
	}
	return u.HomeDir
}

// StateDir returns the lighthouse-only state directory (~/.fleet or FLEET_STATE_DIR).
func StateDir() string {
	if v := os.Getenv("FLEET_STATE_DIR"); v != "" {
		return v
	}
	return filepath.Join(homeDir(), ".fleet")
}

// StateDirForOwner returns FLEET_STATE_DIR if set, otherwise <owner_home>/.fleet (falling back to StateDir).
func StateDirForOwner(owner string) string {
	if v := os.Getenv("FLEET_STATE_DIR"); v != "" {
		return v
	}
	if h := HomeForUser(owner); h != "" {
		return filepath.Join(h, ".fleet")
	}
	return StateDir()
}

