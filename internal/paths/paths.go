// InstalledBinaryPath returns the root-owned installed Go binary location.
func InstalledBinaryPath() string {
	if v := os.Getenv("FLEET_INSTALL_BIN"); v != "" {
		return v
	}
	return DefaultInstalledBinary
}

// SymlinkPath returns the PATH symlink pointing to InstalledBinaryPath.
func SymlinkPath() string {
	if v := os.Getenv("FLEET_BIN_SYMLINK"); v != "" {
		return v
	}
	if info, err := os.Stat(filepath.Dir(DefaultBrewSymlink)); err == nil && info.IsDir() {
		return DefaultBrewSymlink
	}
	return DefaultLocalSymlink
}

// LauncherPath returns the executable path to write into agent MCP and hook configs.
// Prefers /opt/homebrew/bin/fleet when present to preserve existing Codex hook trust hashes.
func LauncherPath() string {
	if v := os.Getenv("FLEET_BIN"); v != "" {
		return v
	}
	if _, err := os.Stat(DefaultBrewSymlink); err == nil {
		return DefaultBrewSymlink
	}
	sym := SymlinkPath()
	if _, err := os.Stat(sym); err == nil {
		return sym
	}
	inst := InstalledBinaryPath()
	if _, err := os.Stat(inst); err == nil {
		return inst
	}
	if exe, err := os.Executable(); err == nil && exe != "" {
		return exe
	}
	return DefaultBrewSymlink
}

// ValidHarness reports whether name is a supported agent harness.
func ValidHarness(name string) bool {
	return slices.Contains(Harnesses, name)
}

// ValidGroup reports whether group is a supported device group.
func ValidGroup(group string) bool {
	return slices.Contains(Groups, group)
}

// LocalStateRoot returns XDG_STATE_HOME if set, otherwise ~/.local/state.
func LocalStateRoot() string {
	if v := os.Getenv("XDG_STATE_HOME"); v != "" {
		return v
	}
	return filepath.Join(homeDir(), ".local", "state")
}

// SessionStateDir returns the per-harness session state directory under LocalStateRoot.
func SessionStateDir(harness string) string {
	return filepath.Join(LocalStateRoot(), "fleet-session", harness)
}

// SlackerLocalStateDir returns the local worker state directory under LocalStateRoot.
func SlackerLocalStateDir() string {
	return filepath.Join(LocalStateRoot(), "fleet-slacker")
}

// AgentRelayStateDir returns the local agent relay state directory under LocalStateRoot.
func AgentRelayStateDir() string {
	return filepath.Join(LocalStateRoot(), "fleet-relay")
}

// ObsidianSyncLabelFor returns the LaunchAgent label for the primary ("agent") or a named extra vault.
func ObsidianSyncLabelFor(name string) string {
	clean := strings.ToLower(strings.TrimSpace(name))
	if clean == "" || clean == "agent" {
		return ObsidianSyncLabel
	}
	return ObsidianSyncLabel + "." + clean
}
