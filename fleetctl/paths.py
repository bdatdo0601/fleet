"""Locations and constants. Paths are read from the environment on each call so
tests (and unusual installs) can redirect them."""

from __future__ import annotations

import ipaddress
import os
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TEMPLATES = REPO / "templates"

MESH = ipaddress.ip_network("10.213.0.0/16")
MESH_PREFIX = MESH.prefixlen
LIGHTHOUSE_IP = "10.213.0.1"
GROUPS = ("admin", "managed")
NAME_PATTERN = r"^[a-z0-9][a-z0-9-]{0,31}$"

MOBILE_CERT_HOURS = 8760  # phones/tablets: 1 year, re-sign with `fleet set`
CA_HOURS = 43800  # 5 years

LABEL_PREFIX = "io.github.bdatdo0601.fleet"
SERVE_LABEL = f"{LABEL_PREFIX}.serve"
SYNC_LABEL = f"{LABEL_PREFIX}.sync"
DDNS_LABEL = f"{LABEL_PREFIX}.ddns"
# `sudo brew services start nebula` names the launchd job sh.brew.nebula (Homebrew 7+)
# or homebrew.mxcl.nebula (older). system.nebula_label() picks whichever is installed.
NEBULA_LABELS = ("sh.brew.nebula", "homebrew.mxcl.nebula")
SYNC_INTERVAL_SECONDS = 300


def api_port() -> int:
    return int(os.environ.get("FLEET_API_PORT", "7443"))


def state_dir() -> Path:
    """Lighthouse-only state: registry DB and CA. Owned by the admin user."""
    return Path(os.environ.get("FLEET_STATE_DIR", str(Path.home() / ".fleet")))


def nebula_etc() -> Path:
    """Directory the Homebrew nebula service loads (*.yml) and keeps PKI in."""
    return Path(os.environ.get("FLEET_NEBULA_ETC", "/opt/homebrew/etc/nebula"))


def node_file() -> Path:
    """Per-machine fleet identity: {"name": ..., "api": ...}. JSON, so nebula ignores it."""
    return nebula_etc() / "fleet.json"


def pending_dir() -> Path:
    """Keys generated by `fleet join` while waiting for approval."""
    return Path(os.environ.get("FLEET_PENDING_DIR", str(Path.home() / ".fleet-join")))
